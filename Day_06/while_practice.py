# Program 1 - Print 1 to 10

i = 1
while i <= 10:
    print(i)
    i = i + 1


# Program 2 - Print 10 to 1

i = 10
while i >= 1:
    print(i)
    i = i - 1


# Program 3 - Even Numbers

i = 1
while i <= 20:
    if i % 2 == 0:
        print(i)
    i = i + 1


# Program 4 - Odd Numbers

i = 1
while i <= 20:
    if i % 2 != 0:
        print(i)
    i = i + 1
